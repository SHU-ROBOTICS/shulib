// goldens.mjs — the route builder's goldens: read them, and RE-MAKE them (chunk RMP1-A1).
//
//   node tools/route_maker/goldens.mjs --write
//
// For every test/goldens/route_maker/*.route.json: rewrite it in the project file's canonical form
// (load -> save) and write its export, `<name>.cpp` (exportRegion + a final newline) — the file the C++
// suite compiles and runs (test/route_maker_golden_test.cpp). test/export.test.mjs fails when a committed
// golden differs from what this would write; run this, then READ the diff before committing it.
// gl0_empty.cpp is NOT one of them: it is §6.3's contract text, kept by hand (no route.json), so the exporter
// is held to it (export.test.mjs's GL0) instead of re-making it.
//
// The golden routes are TEST routes on the suite's fixture robots (and smoke routes on robots one and
// two): placeholders that exercise the exporter and the library, never a route for the team (G4).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadProject, saveProject } from './src/model/project.mjs';
import { exportRegion } from './src/model/export.mjs';

export const GOLDEN_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'test', 'goldens', 'route_maker');

/** Every golden: [name, its canonical project text, its export text]. */
export function goldens() {
    const out = [];
    for (const f of fs.readdirSync(GOLDEN_DIR).filter((n) => n.endsWith('.route.json')).sort()) {
        const name = f.slice(0, -'.route.json'.length);
        const text = fs.readFileSync(path.join(GOLDEN_DIR, f), 'utf8');
        const loaded = loadProject(text);
        if (!loaded.ok) {
            throw new Error(`${f}: ${loaded.words}`);
        }
        out.push([name, saveProject(loaded.project), `${exportRegion(loaded.project.routes[0])}\n`]);
    }
    return out;
}

if (process.argv.includes('--write')) {
    for (const [name, project, cpp] of goldens()) {
        fs.writeFileSync(path.join(GOLDEN_DIR, `${name}.route.json`), project);
        fs.writeFileSync(path.join(GOLDEN_DIR, `${name}.cpp`), cpp);
        console.log(`wrote ${name}.route.json and ${name}.cpp`);
    }
}

// ── RMP1-B: the controls agreement, the CT21 goldens and FE2's rows ─────────────────────────────────
import { cases as ctCases, goldens as ctGoldens, translationUnit, ROBOTS, TABLE } from './controls_cases.mjs';
import { exportRegions } from './src/model/driver_file.mjs';
import { axisValid } from './src/model/feel.mjs';

export const REFUSALS_DIR = path.join(GOLDEN_DIR, '..', '..', 'compile_refusals');
const GENERATED = '// GENERATED by tools/route_maker/goldens.mjs --write (chunk RMP1-B) -- do not edit; re-make it and read the diff.';

/** Every controls-agreement TU: [file name, text]. */
export function refusalTUs() {
    return ctCases().map((k) => [`rm_ct_${k.name}.cpp`, translationUnit(k, [
        `// rm_ct_${k.name}: the route builder REFUSES this configuration on robot ${k.robot} (its checkControls, test/controls.test.mjs) —`,
        '// and the build must refuse it with the SAME name: the C++ is the final authority (the RMP1 brief\'s CT agreement).',
        GENERATED,
    ]) + `// expect: ${k.expect}\n`]);
}

/** Every CT21 golden: [file name, text] — a configuration every rule passes, its three regions in its own namespace. */
export function controlsGoldens() {
    const ns = { x: 'mech_fixture::robot_x', y: 'mech_fixture::robot_y', one: 'shulib::bench::robot_one' };
    return ctGoldens().map((g) => {
        const r = exportRegions({ controls: g.controls || { list: g.list, table: TABLE[g.robot] }, driving: g.driving }, ROBOTS()[g.robot]);
        const n = `${ns[g.robot]}::rm_golden_${g.name}`;
        return [`controls_${g.name}.hpp`, [`// controls_${g.name}: CT21 -- a configuration the route builder passes on robot ${g.robot}, as it writes it.`,
            GENERATED, `namespace ${n} {`, 'using namespace shulib::mechanism::words;', ...r.controls, ...r.feel,
            'static_assert(sizeof(shulib::bench::DriverFile<kControls, kFeel, kLoop>) > 0);  // DriverFile\'s own checks run',
            `inline constexpr std::size_t kCount = ${g.list.length};`, `}  // namespace ${n}`, ''].join('\n')];
    });
}

/** A double as a C++ hex-float literal (exact). */
export function hexDouble(v) {
    if (Number.isNaN(v)) {
        return 'std::numeric_limits<double>::quiet_NaN()';
    }
    if (v === 0) {
        return Object.is(v, -0) ? '-0x0p+0' : '0x0p+0';
    }
    const dv = new DataView(new ArrayBuffer(8));
    dv.setFloat64(0, v);
    const bits = dv.getBigUint64(0);
    const sign = bits >> 63n ? '-' : '';
    const exp = Number((bits >> 52n) & 0x7ffn);
    const mant = (bits & 0xfffffffffffffn).toString(16).padStart(13, '0').replace(/0+$/, '');
    if (exp === 0x7ff) {
        throw new Error(`hexDouble: ${v} has no C++ literal (write it as std::numeric_limits<double>::infinity())`);
    }
    if (exp === 0) {  // subnormal: no hidden 1
        return `${sign}0x0.${mant}p-1022`;
    }
    return `${sign}0x1${mant ? `.${mant}` : ''}p${exp - 1023 >= 0 ? '+' : ''}${exp - 1023}`;
}

/** FE2's boundary rows: [deadband, curve]. */
export const FE2_ROWS = (() => {
    const d = [-1e-12, 0, 1 - 2 ** -53, 1, Number.NaN];
    const e = [-1e-12, 0, 1, 1 + 1e-12, Number.NaN];
    return d.flatMap((x) => e.map((y) => [x, y]));
})();

/** FE2's C++ twin: one static_assert per row, its answer the page's (axisValid). */
export function feelRowsHeader() {
    return ['// feel_valid_rows: FE2 -- each row\'s AxisShaping::valid() as the route builder\'s checkFeel answers it.', GENERATED,
            '#include <limits>', '#include "shulib/teleop/input_shaping.hpp"',
            ...FE2_ROWS.map(([db, ex]) => `static_assert(shulib::teleop::AxisShaping{${hexDouble(db)}, ${hexDouble(ex)}}.valid() == ${axisValid({ deadband: db, expo: ex })});`),
            ''].join('\n');
}

if (process.argv.includes('--write')) {
    for (const f of fs.readdirSync(REFUSALS_DIR).filter((n) => n.startsWith('rm_ct_'))) {
        fs.unlinkSync(path.join(REFUSALS_DIR, f));  // a renamed case leaves no orphan
    }
    for (const [name, text] of refusalTUs()) {
        fs.writeFileSync(path.join(REFUSALS_DIR, name), text);
    }
    for (const [name, text] of controlsGoldens()) {
        fs.writeFileSync(path.join(GOLDEN_DIR, name), text);
    }
    fs.writeFileSync(path.join(GOLDEN_DIR, 'feel_valid_rows.hpp'), feelRowsHeader());
    console.log(`wrote ${refusalTUs().length} rm_ct_*.cpp, ${controlsGoldens().length} controls_*.hpp and feel_valid_rows.hpp`);
}
